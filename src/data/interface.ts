export function localizeInterface(text: string, language: TranslationLanguage): string {
  if (language === 'ru') return text;
  const directTranslation = kyrgyzInterface[text] ?? kyrgyzLessonText[text];
  if (directTranslation !== undefined) return directTranslation;
  if (hasKyrgyzTranslation(text)) return localizeTranslation(text, 'ky');
  const writingPrompt = /^Напишите по-арабски слово со страницы (\d+) книги\.$/u.exec(text);
  if (writingPrompt) return `Китептин ${writingPrompt[1]}-бетиндеги сөздү арабча жазыңыз.`;
  const explanation = /^Сверьте (слово и перевод|форму и перевод|женскую форму и перевод|форму глагола и перевод|глагол и перевод|название родственника) на странице (\d+) книги\.$/u.exec(text);
  if (explanation) {
    const subject = {
      'слово и перевод': 'Сөздү жана котормосун',
      'форму и перевод': 'Форманы жана котормосун',
      'женскую форму и перевод': 'Аял тектеги форманы жана котормосун',
      'форму глагола и перевод': 'Этиштин формасын жана котормосун',
      'глагол и перевод': 'Этишти жана котормосун',
      'название родственника': 'Туугандын аталышын',
    }[explanation[1]!]!;
    return `${subject} китептин ${explanation[2]}-бетинен текшериңиз.`;
  }
  return text;
}

export function hasInterfaceTranslation(text: string): boolean {
  return (
    kyrgyzInterface[text] !== undefined ||
    kyrgyzLessonText[text] !== undefined ||
    hasKyrgyzTranslation(text) ||
    /^Напишите по-арабски слово со страницы \d+ книги\.$/u.test(text) ||
    /^Сверьте (слово и перевод|форму и перевод|женскую форму и перевод|форму глагола и перевод|глагол и перевод|название родственника) на странице \d+ книги\.$/u.test(text)
  );
}

const kyrgyzWeekdays = ['Жек', 'Дүй', 'Шей', 'Шар', 'Бей', 'Жум', 'Ише'];

export function formatWeekday(date: Date, language: TranslationLanguage): string {
  if (language === 'ky') return kyrgyzWeekdays[date.getDay()]!;
  return new Intl.DateTimeFormat('ru', { weekday: 'short' }).format(date);
}

const kyrgyzMonths = [
  'январь', 'февраль', 'март', 'апрель', 'май', 'июнь',
  'июль', 'август', 'сентябрь', 'октябрь', 'ноябрь', 'декабрь',
];

export function formatInterfaceDate(date: Date, language: TranslationLanguage): string {
  if (language === 'ky') {
    return `${date.getDate()}-${kyrgyzMonths[date.getMonth()]} ${date.getFullYear()}`;
  }
  return new Intl.DateTimeFormat('ru', { dateStyle: 'medium' }).format(date);
}
